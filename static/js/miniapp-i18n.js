  var lang = "ru";

  function readCookie(name) {
    var match = document.cookie.match(new RegExp("(?:^|; )" + name + "=([^;]*)"));
    return match ? decodeURIComponent(match[1]) : "";
  }

  function telegramLang() {
    var user = root.Telegram && root.Telegram.WebApp && root.Telegram.WebApp.initDataUnsafe && root.Telegram.WebApp.initDataUnsafe.user;
    var code = String((user && user.language_code) || "").toLowerCase();
    if (code.indexOf("uz") === 0) return "uz";
    return "";
  }

  function detect() {
    try {
      var stored = localStorage.getItem("temina_lang");
      if (LANGS.indexOf(stored) >= 0) return stored;
    } catch (e) {}
    var cookie = readCookie("temina_lang");
    if (LANGS.indexOf(cookie) >= 0) return cookie;
    var fromTg = telegramLang();
    if (fromTg) return fromTg;
    return "ru";
  }

  function t(key, vars) {
    var table = I18N[lang] || I18N.ru;
    var text = table[key] || I18N.ru[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (name) {
        text = String(text).split("{" + name + "}").join(String(vars[name]));
      });
    }
    return text;
  }

  function plural(n, oneKey, fewKey, manyKey) {
    n = Math.abs(Number(n) || 0);
    if (lang === "uz") return t(n === 1 ? oneKey : manyKey);
    var n10 = n % 10;
    var n100 = n % 100;
    if (n10 === 1 && n100 !== 11) return t(oneKey);
    if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return t(fewKey);
    return t(manyKey);
  }

  function applyChrome() {
    document.documentElement.lang = lang === "uz" ? "uz" : "ru";
    document.title = t("meta.title");
    document.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.textContent = t(node.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (node) {
      node.setAttribute("aria-label", t(node.getAttribute("data-i18n-aria")));
    });
    var nav = document.querySelector(".bottom-nav");
    if (nav) nav.setAttribute("aria-label", t("nav.main"));
  }

  function setLang(next) {
    if (LANGS.indexOf(next) < 0) next = "ru";
    lang = next;
    try { localStorage.setItem("temina_lang", next); } catch (e) {}
    document.cookie = "temina_lang=" + encodeURIComponent(next) + ";path=/;max-age=31536000;samesite=lax";
    fetch("/set-language/?lang=" + encodeURIComponent(next) + "&next=/app/", { credentials: "same-origin" }).catch(function () {});
    applyChrome();
  }

  lang = detect();
  applyChrome();
  root.TeminaI18n = {
    t: t,
    plural: plural,
    lang: function () { return lang; },
    setLang: setLang,
    applyChrome: applyChrome,
    langs: LANGS
  };
